import { line, shape, fill, circ, svg, ban, head, maru, write, floor, R } from '../lib.mjs';

const wave = (x, y, n, h = 10, w = 22, c = R, sw = 7) => {
  let d = `M${x} ${y}`;
  for (let i = 0; i < n; i++) d += ` C ${x + w * i + w * 0.3} ${y - h} ${x + w * i + w * 0.7} ${y + h} ${x + w * (i + 1)} ${y}`;
  return line(d, sw, c);
};
const flame = (x, y, s = 1) => fill(`M${x} ${y} C ${x - 14 * s} ${y - 14 * s} ${x - 8 * s} ${y - 30 * s} ${x + 2 * s} ${y - 44 * s} C ${x + 4 * s} ${y - 28 * s} ${x + 16 * s} ${y - 22 * s} ${x + 12 * s} ${y} Z`, R);
// エンジンの発電機（箱・横の排気の管・下の車輪）。x,y は左上
