import { line, shape, fill, ell, svg, batsu, head, write, R } from '../lib.mjs';

const wave = (x, y, n, h = 12, w = 24, c = R, sw = 7) => {
  let d = `M${x} ${y}`;
  for (let i = 0; i < n; i++) d += ` C ${x + w * i + w * 0.3} ${y - h} ${x + w * i + w * 0.7} ${y + h} ${x + w * (i + 1)} ${y}`;
  return line(d, sw, c);
};
